"""Manual independent oracles, abstract Lean and actual source compiler/SDK.
No expected arithmetic is generated by Yuho. This is not compiler refinement.
"""
import json,subprocess,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
EXPECTED=['K:1000000','K:999999','K:-3','U','K:4','U','K:1200','U','K:2','U','K:0','K:27021597764222979','K:0','K:-14','U']
def main():
    out=Path(tempfile.mkdtemp(prefix='yuho-quantitative-conformance-'));commands=[]
    def run(argv,cwd=ROOT):
        p=subprocess.run(list(map(str,argv)),cwd=cwd,capture_output=True,text=True)
        commands.append(dict(argv=list(map(str,argv)),cwd=str(cwd),exit=p.returncode,stdout=p.stdout,stderr=p.stderr))
        (out/'commands.json').write_text(json.dumps(commands,indent=2));assert p.returncode==0,commands[-1];return p.stdout
    run(['lake','build','Yuho.CoreYuho.Quantitative'],ROOT/'mechanisation')
    lean=run(['lake','env','lean','--run','scripts/QuantitativeConformance.lean'],ROOT/'mechanisation').splitlines()
    run(['cabal','exec','--offline','--','ghc-9.8.4','-package=yuho','-outputdir',out/'sdk-build','-o',out/'sdk',ROOT/'test/QuantitativeClient.hs'])
    actual=run([out/'sdk','vectors']).splitlines()
    binary=run(['cabal','list-bin','exe:yuho','--offline','--with-compiler=ghc-9.8.4']).strip()
    examples=[('sum(item a value integer(400000),item b value integer(600000))','integer',[]),
      ('sum(item a value integer(400000),item b value integer(599999))','integer',[]),
      ('sum(item a value integer(1),item b value integer(-4))','integer',[]),
      ('sum(item a value integer(4),item b value ref(v:unknown))','integer',[]),
      ('sum(item a value integer(4),item b value ref(v:unknown) when q:no)','integer',[]),
      ('sum(item a value integer(4),item b value integer(0) when q:unknown)','integer',[]),
      ('scale(3,sum(item a value integer(125),item b value integer(275)))','integer',[]),
      ('scale(0,ref(v:unknown))','integer',[]),
      ('count(item a when q:yes,item b when q:no,item c when q:yes)','count occasions',[]),
      ('count(item a when q:yes,item b when q:unknown)','count occasions',[]),
      ('sum()','integer',[]),('scale(3,integer(9007199254740993))','integer',[]),
      ('count()','count occasions',[]),('scale(-2,integer(7))','integer',[]),
      ('sum(item a value integer(0),item b value integer(0) when q:unknown)','integer',[])]
    source=[]
    for i,(expr,ty,_) in enumerate(examples):
      model=out/f'vector-{i}.yh';scenario=out/f'vector-{i}.scenario.yh'
      model.write_text('typed-rules-model Vector { quantitative version "yuho.quantitative/v0.1-experimental";\n'
        'entity-type person; entity actor as person; predicate yes(person) kind circumstance; predicate no(person) kind circumstance; predicate unknown(person) kind circumstance;\n'
        'requirement q:yes = yes(actor); requirement q:no = no(actor); requirement q:unknown = unknown(actor);\n'
        'scalar v:unknown type integer; derive v:out type '+ty+' = '+expr+';\n'
        'proposition p; rule r establishes proposition p when q:yes; limitation "Independent mathematical vector"; }')
      scenario.write_text('typed-rules-scenario Selected for Vector { value v:unknown = unresolved reason "explicit unknown";\n'
        'classify yes(actor) as proved reason "manual true"; classify no(actor) as not_proved reason "manual false"; classify unknown(actor) as unresolved reason "manual unknown"; }')
      value=json.loads(run([binary,'run',model,'--scenario',scenario]))['quantitative']['values']['v:out']
      source.append('K:'+value['integer'] if value['state']=='known_exact' else 'U')
    assert EXPECTED==lean==actual==source,(EXPECTED,lean,actual,source)
    (out/'results.json').write_text(json.dumps(dict(expected=EXPECTED,lean=lean,production_sdk=actual,production_source=source),indent=2))
    print(json.dumps(dict(vectors=len(EXPECTED),status='passed',output=str(out))))
if __name__=='__main__':main()
